#!/usr/bin/env node
// Generates src/content/types.ts from the JSON Schemas in content/schema (the schemas are the source of truth;
// src/content/schemas.ts mirrors them in Zod and tests/content checks the two agree).
// Usage: node scripts/gen-types.mjs [--check]
//   --check  exit 1 when src/content/types.ts is not what the schemas generate (CI drift guard).
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { compile } from 'json-schema-to-typescript';

const ROOT = process.cwd();
const SCHEMA_DIR = path.join(ROOT, 'content/schema');
const OUT = path.join(ROOT, 'src/content/types.ts');
const SCHEMAS = ['exhibit.schema.json', 'story.schema.json', 'image-meta.schema.json'];
const check = process.argv.includes('--check');

const BANNER = [
  '/* eslint-disable */',
  '/**',
  ' * Generated by scripts/gen-types.mjs from content/schema/*.json. Do not edit by hand:',
  ' * change the schema, then run `pnpm gen:types`.',
  ' */',
].join('\n');

async function typesFor(file) {
  const schema = JSON.parse(await readFile(path.join(SCHEMA_DIR, file), 'utf8'));
  // Conditional publication rules (allOf + if/then) have no TypeScript equivalent; the validator enforces them.
  delete schema.allOf;
  return compile(schema, schema.title, {
    bannerComment: '',
    cwd: SCHEMA_DIR,
    additionalProperties: false,
    strictIndexSignatures: true,
    style: { singleQuote: true, printWidth: 120, trailingComma: 'all' },
  });
}

const parts = [];
for (const file of SCHEMAS) parts.push((await typesFor(file)).trim());
const output = `${BANNER}\n\n${parts.join('\n\n')}\n`;

if (check) {
  const current = await readFile(OUT, 'utf8').catch(() => '');
  if (current.replace(/\r\n/g, '\n') !== output) {
    console.error(
      'src/content/types.ts is out of date with content/schema. Run `pnpm gen:types` and commit the result.',
    );
    process.exit(1);
  }
  console.log('gen-types: src/content/types.ts is up to date');
} else {
  await writeFile(OUT, output);
  console.log(`gen-types: wrote ${path.relative(ROOT, OUT)} from ${SCHEMAS.length} schemas`);
}
